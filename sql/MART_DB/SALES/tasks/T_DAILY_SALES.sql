CREATE OR REPLACE TASK MART_DB.SALES.T_DAILY_SALES
    WAREHOUSE = WH_MART_XS
    SCHEDULE = 'USING CRON 30 6 * * * Asia/Tokyo'
AS
INSERT INTO MART_DB.SALES.DAILY_SALES (SALES_DATE, PREFECTURE, CHANNEL, ORDER_COUNT, TOTAL_AMOUNT)
SELECT
    o.ORDER_DATE,
    c.PREFECTURE,
    o.CHANNEL,
    COUNT(DISTINCT o.ORDER_ID) AS ORDER_COUNT,
    SUM(o.ORDER_AMOUNT) AS TOTAL_AMOUNT
FROM DWH_DB.CORE.FCT_ORDERS o
JOIN DWH_DB.CORE.DIM_CUSTOMER c USING (CUSTOMER_ID)
WHERE o.ORDER_DATE = CURRENT_DATE - 1
GROUP BY 1, 2, 3;
