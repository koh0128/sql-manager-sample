CREATE OR REPLACE VIEW MART_DB.MARKETING.V_CHANNEL_CONVERSION AS
SELECT
    pv.VIEW_DATE,
    pv.SOURCE_CHANNEL,
    COUNT(DISTINCT pv.SESSION_ID) AS SESSIONS,
    COUNT(DISTINCT o.ORDER_ID)    AS ORDERS,
    COUNT(DISTINCT o.ORDER_ID) / NULLIF(COUNT(DISTINCT pv.SESSION_ID), 0) AS CVR
FROM DWH_DB.CORE.FCT_PAGE_VIEWS pv
LEFT JOIN DWH_DB.CORE.FCT_ORDERS o
    ON o.CUSTOMER_ID = pv.CUSTOMER_ID
   AND o.ORDER_DATE = pv.VIEW_DATE
GROUP BY 1, 2;
