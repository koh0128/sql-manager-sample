CREATE OR REPLACE TASK DWH_DB.CORE.T_LOAD_ORDERS
    WAREHOUSE = WH_ETL_XS
    SCHEDULE = '5 MINUTE'
    WHEN SYSTEM$STREAM_HAS_DATA('RAW_DB.EC.ORDERS_RAW_STREAM')
AS
MERGE INTO DWH_DB.CORE.FCT_ORDERS t
USING RAW_DB.EC.ORDERS_RAW_STREAM s
    ON t.ORDER_ID = s.ORDER_ID
WHEN MATCHED THEN UPDATE SET ORDER_STATUS = UPPER(s.STATUS)
WHEN NOT MATCHED THEN INSERT (ORDER_ID, CUSTOMER_ID, ORDER_DATE, ORDER_AMOUNT, ORDER_STATUS, CHANNEL)
    VALUES (s.ORDER_ID, s.CUSTOMER_ID, TO_DATE(s.ORDER_TS), s.TOTAL, UPPER(s.STATUS), s.CHANNEL);
