-- Airflow DAG `dim_daily` が毎日 02:20 に実行する
CREATE OR REPLACE TABLE DWH_DB.CORE.DIM_CUSTOMER AS
SELECT
    c.CUSTOMER_ID,
    p.PREF_NAME AS PREFECTURE,
    c.SIGNUP_DATE,
    FLOOR(DATEDIFF(year, c.BIRTH_DATE, CURRENT_DATE) / 10) * 10 AS AGE_BAND
FROM RAW_DB.EC.CUSTOMERS_RAW c
LEFT JOIN RAW_DB.EC.PREF_MASTER p
    ON p.PREF_CODE = c.PREF;
