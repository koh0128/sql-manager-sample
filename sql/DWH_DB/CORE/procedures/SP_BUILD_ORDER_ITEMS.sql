CREATE OR REPLACE PROCEDURE DWH_DB.CORE.SP_BUILD_ORDER_ITEMS()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
    CREATE OR REPLACE TABLE DWH_DB.CORE.FCT_ORDER_ITEMS AS
    SELECT i.ORDER_ID, i.LINE_NO, i.PRODUCT_ID, i.QTY,
           i.QTY * i.UNIT_PRICE AS LINE_AMOUNT
    FROM RAW_DB.EC.ORDER_ITEMS_RAW i
    JOIN DWH_DB.CORE.DIM_PRODUCT p USING (PRODUCT_ID);
    RETURN 'ok';
END;
$$;
